<?php

declare(strict_types=1);

namespace App\Plan\Selector;

/**
 * Декларация того, какие строки таблицы принадлежат пользователю.
 *
 * Селектор — данные, а не запрос: он не знает ни о Query Builder, ни о подключении.
 * Превращением в SQL занимается отдельный компилятор, поэтому новый вид принадлежности
 * добавляется новым классом селектора и новым компилятором, без правки существующих.
 */
interface Selector
{
    /**
     * Машинный тип селектора — по нему подбирается компилятор.
     */
    public function type(): string;

    /**
     * Колонки целевой таблицы, которые обязаны существовать в схеме.
     * Используется preflight-проверкой до начала операции.
     *
     * @return array<int, string>
     */
    public function columns(): array;

    /**
     * Наборы значений скоупа, которые нужны селектору для работы.
     *
     * @return array<int, \App\Plan\ScopeKey>
     */
    public function scopeKeys(): array;
}
